const OFL_TEXT = `SIL OPEN FONT LICENSE Version 1.1 - 26 February 2007
Permission is hereby granted, free of charge, to any person obtaining
a copy of the Font Software, to use, study, copy, merge, embed, modify,
redistribute, and sell modified and unmodified copies of the Font Software.`;

const APACHE_TEXT = `Apache License Version 2.0, January 2004
http://www.apache.org/licenses/
Licensed under the Apache License, Version 2.0.`;

for (const font of FONTS) {
  const fontDir = path.join(CONTENT_FONTS, font.slug);
  fs.mkdirSync(fontDir, { recursive: true });

  const licenseFile = font.license === "Apache-2.0" ? "LICENSE.txt" : "OFL.txt";
  const licenseContent = font.license === "Apache-2.0" ? APACHE_TEXT : OFL_TEXT;
  fs.writeFileSync(path.join(fontDir, licenseFile), licenseContent, 'utf8');

  const meta = {
    slug: font.slug,
    kind: "font",
    name: font.name,
    family: font.family,
    description: font.description,
    author: font.author,
    tags: [font.category, "typography", font.slug],
    category: font.category,
    license: font.license,
    fontsourcePackage: font.fontsourcePackage,
    weights: font.weights,
    subsets: font.subsets,
    variable: font.variable,
    source: font.source,
    licenseFile: licenseFile,
  };

  fs.writeFileSync(path.join(fontDir, "font.json"), JSON.stringify(meta, null, 2) + "\n", 'utf8');

  // Also prepare public/fonts/<slug>/ directory
  const pubDir = path.join(PUBLIC_FONTS, font.slug);
  fs.mkdirSync(pubDir, { recursive: true });
  fs.writeFileSync(
    path.join(pubDir, "README.md"),
    `# ${font.name} Local Font Files\n\nPlace your .woff2 or .woff files in this folder:\n- \`${font.name}-Regular.woff2\`\n- \`${font.name}-Bold.woff2\`\n\nSee /docs for Next.js \`next/font/local\` and CSS \`@font-face\` configuration examples.\n`,
    'utf8'
  );
}

fs.writeFileSync(
  path.join(PUBLIC_FONTS, "README.md"),
  `# Public Fonts Storage\n\nThis directory contains self-hosted font assets organized by family slug (\`public/fonts/<slug>/\`).\nSupported formats: .woff2 (recommended), .woff.\n`,
  'utf8'
);

console.log(`Successfully generated ${FONTS.length} font resources in content/fonts/ and public/fonts/`);
