// Fetch devicon.json to know exact versions and official hex colors
const deviconJsonRes = await fetch("https://raw.githubusercontent.com/devicons/devicon/master/devicon.json");
const deviconCatalog: Array<{
  name: string;
  color?: string;
  versions: { svg: string[] };
}> = (await deviconJsonRes.json()) as Array<{
  name: string;
  color?: string;
  versions: { svg: string[] };
}>;

const catalogMap = new Map<string, { color?: string; versions: string[] }>();
for (const item of deviconCatalog) {
  catalogMap.set(item.name.toLowerCase(), {
    color: item.color,
    versions: item.versions?.svg || [],
  });
}

let addedCount = 0;
let skippedCount = 0;

for (const target of TARGET_LOGOS) {
  const targetDir = join(CONTENT_LOGOS, target.slug);

  // Check if logo already exists with valid meta.json
  try {
    await readFile(join(targetDir, "meta.json"), "utf8");
    console.log(`[SKIP] Logo "${target.slug}" already exists in content/logos/`);
    skippedCount++;
    continue;
  } catch {
    // does not exist, proceed
  }

  const deviconInfo = catalogMap.get(target.deviconName.toLowerCase());
  const versions = deviconInfo?.versions || ["original", "plain"];

  // Priority for color: "original" -> "plain"
  const colorVersion = versions.includes("original") ? "original" : versions[0] || "plain";

  // Priority for mono: "plain" -> "original"
  const monoVersion = versions.includes("plain") ? "plain" : versions.includes("line") ? "line" : colorVersion;

  // Wordmark if available
  const wordmarkVersion = versions.find((v) => v.includes("wordmark"));

  const baseUrl = `https://raw.githubusercontent.com/devicons/devicon/master/icons/${target.deviconName}/${target.deviconName}-`;

  try {
    const colorSvgUrl = `${baseUrl}${colorVersion}.svg`;
    const monoSvgUrl = `${baseUrl}${monoVersion}.svg`;

    const colorSvgRes = await fetch(colorSvgUrl);
    if (!colorSvgRes.ok) throw new Error(`HTTP ${colorSvgRes.status} for color SVG`);
    let colorSvg = await colorSvgRes.text();

    const monoSvgRes = await fetch(monoSvgUrl);
    if (!monoSvgRes.ok) throw new Error(`HTTP ${monoSvgRes.status} for mono SVG`);
    let monoSvg = await monoSvgRes.text();

    // Wordmark SVG
    let wordmarkSvg: string | null = null;
    if (wordmarkVersion) {
      const wmRes = await fetch(`${baseUrl}${wordmarkVersion}.svg`);
      if (wmRes.ok) {
        wordmarkSvg = await wmRes.text();
      }
    }

    // Safety checks: clean forbidden tags
    colorSvg = colorSvg.replace(/<script[\s\S]*?<\/script>/gi, "").replace(/<foreignObject[\s\S]*?<\/foreignObject>/gi, "");
    monoSvg = monoSvg.replace(/<script[\s\S]*?<\/script>/gi, "").replace(/<foreignObject[\s\S]*?<\/foreignObject>/gi, "");
    if (wordmarkSvg) {
      wordmarkSvg = wordmarkSvg.replace(/<script[\s\S]*?<\/script>/gi, "").replace(/<foreignObject[\s\S]*?<\/foreignObject>/gi, "");
    }

    await mkdir(targetDir, { recursive: true });
    await writeFile(join(targetDir, "color.svg"), colorSvg, "utf8");
    await writeFile(join(targetDir, "mono.svg"), monoSvg, "utf8");
    if (wordmarkSvg) {
      await writeFile(join(targetDir, "wordmark.svg"), wordmarkSvg, "utf8");
    }

    const hexColor =
      deviconInfo?.color && /^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/.test(deviconInfo.color)
        ? deviconInfo.color
        : target.defaultHex;

    const variants: Record<string, { file: string; hex?: string }> = {
      color: { file: "color.svg", hex: hexColor },
      mono: { file: "mono.svg" },
    };

    if (wordmarkSvg) {
      variants.wordmark = { file: "wordmark.svg" };
    }

    const meta = {
      slug: target.slug,
      kind: "logo",
      name: target.name,
      description: target.description,
      aliases: target.aliases,
      category: target.category,
      tags: [target.category, target.slug, ...target.aliases],
      license: "trademark",
      author: `${target.name} Team`,
      website: target.website,
      brandGuidelinesUrl: target.brandGuidelinesUrl,
      source: {
        url: colorSvgUrl,
        retrievedAt: "2026-10-29",
      },
      variants,
    };

    await writeFile(join(targetDir, "meta.json"), JSON.stringify(meta, null, 2) + "\n", "utf8");
    console.log(`[ADD] Successfully added "${target.slug}" (${target.name})`);
    addedCount++;
  } catch (err) {
    console.error(`[ERR] Failed to fetch or process "${target.slug}":`, (err as Error).message);
  }
}

console.log(`Finished scraping: added ${addedCount} new logos, skipped ${skippedCount} existing.`);
