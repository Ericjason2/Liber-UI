import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { validateAll } from "./lib/validate-resource.js";
import { optimizeSvgString } from "./lib/optimize-svg.js";
import { generateReactComponent, toPascalCase } from "./lib/build-react.js";
import {
  createLogoRegistryItem,
  createFontRegistryItem,
  createComponentRegistryItem,
  createThemeRegistryItem,
  createRootRegistry,
  type RegistryItem,
} from "./lib/build-registry.js";
import type { LogoMeta, LogoVariant, ResourceMeta } from "./lib/schema.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const ROOT = join(__dirname, "..");
const CONTENT_ROOT = join(ROOT, "content");
const PACKAGES_CORE = join(ROOT, "packages/core");
const PACKAGES_SVG = join(ROOT, "packages/svg");
const PACKAGES_LOGO = join(ROOT, "packages/logo");
const APPS_WEB_PUBLIC = join(ROOT, "apps/web/public");

console.log("Liber Pipeline: Starting generation...");

// Step 1: Validate all resources
console.log("-> 1. Validating resources in content/...");
const report = await validateAll(CONTENT_ROOT);
if (report.issues.length > 0) {
  console.error(`[ERROR] Validation failed with ${report.issues.length} errors:`);
  for (const i of report.issues) {
    console.error(`  - [${i.kind}] ${i.slug}: ${i.message}`);
  }
  process.exit(1);
}
console.log(`[PASS] Validated ${report.totalChecked} resources.`);

// Ensure target directories exist
await mkdir(join(PACKAGES_CORE, "src"), { recursive: true });
await mkdir(join(PACKAGES_SVG, "logos"), { recursive: true });
await mkdir(join(PACKAGES_LOGO, "src/components"), { recursive: true });
await mkdir(join(APPS_WEB_PUBLIC, "r"), { recursive: true });
await mkdir(join(APPS_WEB_PUBLIC, "svg"), { recursive: true });

const allResources: ResourceMeta[] = [];
const registryItems: RegistryItem[] = [];
const reactExports: string[] = [];

// Step 2: Process Logos
console.log("-> 2. Processing logos, optimizing SVGs and generating React components...");
const logosDir = join(CONTENT_ROOT, "logos");
const logoDirEntries = await readdir(logosDir, { withFileTypes: true });
const logosList: string[] = [];

for (const entry of logoDirEntries) {
  if (entry.isDirectory()) {
    try {
      await readFile(join(logosDir, entry.name, "meta.json"), "utf8");
      logosList.push(entry.name);
    } catch {
      // not a logo folder with meta.json
    }
  }
}
logosList.sort();

for (const slug of logosList) {
  const dir = join(logosDir, slug);
  const meta: LogoMeta = JSON.parse(await readFile(join(dir, "meta.json"), "utf8"));
  allResources.push(meta);

  await mkdir(join(PACKAGES_SVG, "logos", slug), { recursive: true });
  await mkdir(join(APPS_WEB_PUBLIC, "svg", slug), { recursive: true });

  const registryFileComponents: string[] = [];
  const variantKeys = Object.keys(meta.variants) as (keyof typeof meta.variants)[];

  for (const vKey of variantKeys) {
    const variantInfo = meta.variants[vKey];
    if (!variantInfo) continue;

    const rawSvg = await readFile(join(dir, variantInfo.file), "utf8");
    const optimized = optimizeSvgString(rawSvg, {
      slug,
      variant: vKey as LogoVariant,
      brandName: meta.name,
    });

    // Write optimized SVG to packages/svg and apps/web/public/svg
    await writeFile(join(PACKAGES_SVG, "logos", slug, `${vKey}.svg`), optimized.svg, "utf8");
    await writeFile(join(APPS_WEB_PUBLIC, "svg", slug, `${vKey}.svg`), optimized.svg, "utf8");

    // Generate React component for this variant
    const pascalBrand = toPascalCase(slug);
    const pascalVariant = toPascalCase(vKey);
    const componentName = `${pascalBrand}${pascalVariant}`;

    const componentCode = await generateReactComponent(optimized.svg, componentName);

    // Save individual component in packages/logo/src/components/${componentName}.tsx
    await writeFile(join(PACKAGES_LOGO, "src/components", `${componentName}.tsx`), componentCode, "utf8");

    reactExports.push(`export * from "./components/${componentName}";`);
    registryFileComponents.push(componentCode);
  }

  // Registry item for shadcn
  const combinedRegistryCode = registryFileComponents.join("\n\n");
  const regItem = createLogoRegistryItem(meta, combinedRegistryCode);
  registryItems.push(regItem);
  await writeFile(join(APPS_WEB_PUBLIC, "r", `${slug}.json`), JSON.stringify(regItem, null, 2) + "\n", "utf8");
}

// Write packages/logo/src/index.ts
const reactIndexContent = `// Generated by @liber/scripts - DO NOT EDIT MANUALLY\n${reactExports.join("\n")}\n`;
await writeFile(join(PACKAGES_LOGO, "src/index.ts"), reactIndexContent, "utf8");

// Step 2b: Process Fonts
console.log("-> 2b. Processing fonts from content/fonts/...");
const fontsDir = join(CONTENT_ROOT, "fonts");
try {
  const fontDirEntries = await readdir(fontsDir, { withFileTypes: true });
  for (const entry of fontDirEntries) {
    if (!entry.isDirectory()) continue;
    try {
      const fontJson = await readFile(join(fontsDir, entry.name, "font.json"), "utf8");
      const fontMeta = JSON.parse(fontJson);
      allResources.push(fontMeta);
      const fontRegItem = createFontRegistryItem(fontMeta);
      registryItems.push(fontRegItem);
      await writeFile(join(APPS_WEB_PUBLIC, "r", `${entry.name}.json`), JSON.stringify(fontRegItem, null, 2) + "\n", "utf8");
      await writeFile(join(APPS_WEB_PUBLIC, "r", `font-${entry.name}.json`), JSON.stringify(fontRegItem, null, 2) + "\n", "utf8");
    } catch {
      // ignore
    }
  }
} catch {
  // fonts dir not present
}

