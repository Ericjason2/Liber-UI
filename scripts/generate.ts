import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { validateAll } from "./lib/validate-resource.js";
import { optimizeSvgString } from "./lib/optimize-svg.js";
import { generateReactComponent, toPascalCase } from "./lib/build-react.js";
import { createLogoRegistryItem, createRootRegistry, type RegistryItem } from "./lib/build-registry.js";
import type { LogoMeta, LogoVariant, ResourceMeta } from "./lib/schema.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const ROOT = join(__dirname, "..");
const CONTENT_ROOT = join(ROOT, "content");
const PACKAGES_CORE = join(ROOT, "packages/core");
const PACKAGES_SVG = join(ROOT, "packages/svg");
const PACKAGES_REACT = join(ROOT, "packages/react");
const APPS_WEB_PUBLIC = join(ROOT, "apps/web/public");

console.log("Liber Pipeline: Starting generation...");

// Step 1: Validate all resources
console.log("-> 1. Validating resources in content/...");
const report = await validateAll(CONTENT_ROOT);
if (report.issues.length > 0) {
  console.error(`[ERROR] Validation failed with ${report.issues.length} errors:`);
  for (const i of report.issues) {
    console.error(`  - [${i.kind}] ${i.slug}: ${i.message}`);
  }
  process.exit(1);
}
console.log(`[PASS] Validated ${report.totalChecked} resources.`);

// Ensure target directories exist
await mkdir(join(PACKAGES_CORE, "src"), { recursive: true });
await mkdir(join(PACKAGES_SVG, "logos"), { recursive: true });
await mkdir(join(PACKAGES_REACT, "src/components"), { recursive: true });
await mkdir(join(APPS_WEB_PUBLIC, "r"), { recursive: true });
await mkdir(join(APPS_WEB_PUBLIC, "svg"), { recursive: true });

const allResources: ResourceMeta[] = [];
const registryItems: RegistryItem[] = [];
const reactExports: string[] = [];

// Step 2: Process Logos
console.log("-> 2. Processing logos, optimizing SVGs and generating React components...");
const logosDir = join(CONTENT_ROOT, "logos");
const logoDirEntries = await readdir(logosDir, { withFileTypes: true });
const logosList: string[] = [];

for (const entry of logoDirEntries) {
  if (entry.isDirectory()) {
    try {
      await readFile(join(logosDir, entry.name, "meta.json"), "utf8");
      logosList.push(entry.name);
    } catch {
      // not a logo folder with meta.json
    }
  }
}
logosList.sort();

for (const slug of logosList) {
  const dir = join(logosDir, slug);
  const meta: LogoMeta = JSON.parse(await readFile(join(dir, "meta.json"), "utf8"));
  allResources.push(meta);

  await mkdir(join(PACKAGES_SVG, "logos", slug), { recursive: true });
  await mkdir(join(APPS_WEB_PUBLIC, "svg", slug), { recursive: true });

  const registryFileComponents: string[] = [];
  const variantKeys = Object.keys(meta.variants) as (keyof typeof meta.variants)[];

  for (const vKey of variantKeys) {
    const variantInfo = meta.variants[vKey];
    if (!variantInfo) continue;

    const rawSvg = await readFile(join(dir, variantInfo.file), "utf8");
    const optimized = optimizeSvgString(rawSvg, {
      slug,
      variant: vKey as LogoVariant,
      brandName: meta.name,
    });

    // Write optimized SVG to packages/svg and apps/web/public/svg
    await writeFile(join(PACKAGES_SVG, "logos", slug, `${vKey}.svg`), optimized.svg, "utf8");
    await writeFile(join(APPS_WEB_PUBLIC, "svg", slug, `${vKey}.svg`), optimized.svg, "utf8");

    // Generate React component for this variant
    const pascalBrand = toPascalCase(slug);
    const pascalVariant = toPascalCase(vKey);
    const componentName = `${pascalBrand}${pascalVariant}`;

    const componentCode = await generateReactComponent(optimized.svg, componentName);

    // Save individual component in packages/react/src/components/${componentName}.tsx
    await writeFile(join(PACKAGES_REACT, "src/components", `${componentName}.tsx`), componentCode, "utf8");

    reactExports.push(`export * from "./components/${componentName}";`);
    registryFileComponents.push(componentCode);
  }

  // Registry item for shadcn
  const combinedRegistryCode = registryFileComponents.join("\n\n");
  const regItem = createLogoRegistryItem(meta, combinedRegistryCode);
  registryItems.push(regItem);
  await writeFile(join(APPS_WEB_PUBLIC, "r", `${slug}.json`), JSON.stringify(regItem, null, 2) + "\n", "utf8");
}

// Write packages/react/src/index.ts
const reactIndexContent = `// Generated by @liber/scripts - DO NOT EDIT MANUALLY\n${reactExports.join("\n")}\n`;
await writeFile(join(PACKAGES_REACT, "src/index.ts"), reactIndexContent, "utf8");

// Step 3: Write Root Registry
console.log("-> 3. Writing shadcn registry files...");
const rootRegistry = createRootRegistry(registryItems);
await writeFile(join(APPS_WEB_PUBLIC, "r/index.json"), JSON.stringify(rootRegistry, null, 2) + "\n", "utf8");
await writeFile(join(APPS_WEB_PUBLIC, "r/registry.json"), JSON.stringify(rootRegistry, null, 2) + "\n", "utf8");

// Step 4: Write Core index and types
console.log("-> 4. Writing @liber/core index.json and TypeScript typings...");
const catalogIndex = {
  version: "0.1.0",
  updatedAt: new Date().toISOString(),
  stats: {
    total: allResources.length,
    logos: allResources.filter((r) => r.kind === "logo").length,
    blocks: allResources.filter((r) => r.kind === "block").length,
    components: allResources.filter((r) => r.kind === "component").length,
    themes: allResources.filter((r) => r.kind === "theme").length,
    fonts: allResources.filter((r) => r.kind === "font").length,
  },
  items: allResources,
};

await writeFile(join(PACKAGES_CORE, "index.json"), JSON.stringify(catalogIndex, null, 2) + "\n", "utf8");
await writeFile(join(APPS_WEB_PUBLIC, "index.json"), JSON.stringify(catalogIndex, null, 2) + "\n", "utf8");

// Export types in @liber/core
const coreTypesCode = `// Generated by @liber/scripts - DO NOT EDIT MANUALLY
export * from "./schema";
import type { ResourceMeta } from "./schema";

export interface CatalogIndex {
  version: string;
  updatedAt: string;
  stats: {
    total: number;
    logos: number;
    blocks: number;
    components: number;
    themes: number;
    fonts: number;
  };
  items: ResourceMeta[];
}
`;
await writeFile(join(PACKAGES_CORE, "src/index.ts"), coreTypesCode, "utf8");

// Copy schema to core/src/schema.ts
const schemaSource = await readFile(join(__dirname, "lib/schema.ts"), "utf8");
await writeFile(join(PACKAGES_CORE, "src/schema.ts"), schemaSource, "utf8");

// Step 5: Packaging bulk downloads & offline backups
console.log("-> 5. Packaging downloadable offline assets and backups...");
const downloadsDir = join(APPS_WEB_PUBLIC, "downloads");
await mkdir(downloadsDir, { recursive: true });

await writeFile(
  join(downloadsDir, "liber-catalog-backup.json"),
  JSON.stringify(catalogIndex, null, 2) + "\n",
  "utf8"
);

try {
  const { execSync } = await import("node:child_process");
  const zipPath = join(downloadsDir, "liber-svg-collection.zip");
  execSync(`tar -a -c -f "${zipPath}" -C "${PACKAGES_SVG}" logos`, { stdio: "ignore" });
  console.log("  [OK] Created liber-svg-collection.zip archive");
} catch (err) {
  console.warn("  [NOTE] Could not create zip archive via tar:", err);
}

console.log("\n[SUCCESS] Liber generation finished successfully!");
console.log(`- ${logosList.length} Logos optimized (color, mono, wordmark)`);
console.log(`- React components generated in @liber/react`);
console.log(`- Raw SVGs in @liber/svg`);
console.log(`- Registry items in apps/web/public/r/*.json`);
console.log(`- Core index in @liber/core/index.json`);
console.log(`- Downloadable offline backups in apps/web/public/downloads/`);
